def render(spu: dict, skus: list[dict], d: dict) -> str:
    cat = spu["cat"]
    name = spu["name"]
    lo, hi = spu["min_price"], spu["max_price"]
    price_txt = f"¥{lo}" if str(lo) == str(hi) else f"¥{lo} - ¥{hi}"
    L: list[str] = []
    L.append(f"# {name} 产品规格与使用指南\n")
    L.append(f"> 品类：{cat}　|　在售价格：{price_txt}　|　在售版本：{len(skus)} 个\n")
    L.append("## 产品概述\n")
    L.append(d["intro"] + "\n")
    L.append("## 一、核心参数\n")
    L.append("| 参数项 | 规格 |")
    L.append("|--------|------|")
    L.append(f"| 产品型号 | {d['m']} |")
    for k, v in d["p"]:
        L.append(f"| {k} | {v} |")
    L.append("")
    if skus:
        L.append("## 二、在售版本与价格\n")
        L.append("| 版本 / 配色 | 规格 | 价格 |")
        L.append("|-------------|------|------|")
        for s in skus:
            spec = (s["specs"] or "").replace(";", " / ").replace(":", "：") or "—"
            L.append(f"| {s['name'].split('·')[-1].strip()} | {spec} | ¥{s['price']} |")
        L.append("")
    L.append("## 三、功能特点\n")
    for i, x in enumerate(d["f"], 1):
        L.append(f"{i}. {x}")
    L.append("")
    if d.get("u"):
        L.append("## 四、安装与使用建议\n")
        for x in d["u"]:
            L.append(f"- {x}")
        L.append("")
    if d.get("c"):
        L.append("## 五、保养与清洁\n")
        for x in d["c"]:
            L.append(f"- {x}")
        L.append("")
    L.append("## 六、包装清单\n")
    for x in d.get("b", DEFAULT_BOX[cat]):
        L.append(f"- {x}")
    L.append("")
    L.append("## 七、价格与售后保障\n")
    L.append(f"- 当前售价：{price_txt}，共 {len(skus)} 个在售版本，以商品详情页实时价格为准")
    L.append(f"- 保修政策：{d.get('w', DEFAULT_WARRANTY[cat])}")
    for x in DEFAULT_POLICY:
        L.append(f"- {x}")
    L.append("")
    if d.get("q"):
        L.append("## 八、常见问题\n")
        for q, a in d["q"]:
            L.append(f"**Q：{q}**")
            L.append(f"A：{a}\n")
    return "\n".join(L).strip() + "\n"


def _clean_product_name(fn: str) -> str:
    n = re.sub(r"\.(md|txt|docx|pdf)$", "", fn, flags=re.I)
    n = re.sub(r"[-_]?产品(参数|规格|信息|说明书)[-_]?", "", n)
    n = re.sub(r"[-_]?spec[s]?[-_]?", "", n, flags=re.I)
    n = re.sub(r"[-_]", " ", n)
    return re.sub(r"\s+", " ", n).strip()


def _norm(s: str) -> str:
    return re.sub(r"[\s\-_·・]+", "", s or "").lower()


# ---------------------------------------------------------------- 主流程
def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--only", default="")
    ap.add_argument("--out-dir", default="")
    args = ap.parse_args()

    conn = pymysql.connect(**DB, cursorclass=pymysql.cursors.DictCursor)
    with conn.cursor() as cur:
        fmt = ",".join(["%s"] * len(MISSING_IDS))
        cur.execute(
            f"""select s.id, s.name, s.min_price, s.max_price, c.name as cat
                from stellar_spu s left join stellar_category c on c.id = s.category_id
                where s.id in ({fmt}) order by s.id""", MISSING_IDS)
        spus = {r["id"]: r for r in cur.fetchall()}
        cur.execute(f"""select spu_id, name, specs, price from stellar_sku
                        where spu_id in ({fmt}) and status = 1 order by spu_id, sort, id""", MISSING_IDS)
        skus: dict[int, list] = {}
        for r in cur.fetchall():
            skus.setdefault(r["spu_id"], []).append(r)
        cur.execute("select filename from stellar_rag_kb_documents")
        existing = {_norm(_clean_product_name(r["filename"])) for r in cur.fetchall()}

    only = {int(x) for x in args.only.split(",") if x.strip()} if args.only else None
    targets = [i for i in MISSING_IDS if (only is None or i in only)]

    docs, skipped = [], []
    for sid in targets:
        spu = spus.get(sid)
        if not spu:
            skipped.append((sid, "SPU 不存在"))
            continue
        if sid not in DATA:
            skipped.append((sid, "未配置生成数据"))
            continue
        if DATA[sid].get("_name") and DATA[sid]["_name"] != spu["name"]:
            skipped.append((sid, f"名称不符: {spu['name']}"))
            continue
        # 已有同名文档则跳过，避免重复入库
        if _norm(spu["name"]) in existing:
            skipped.append((sid, "已有同名文档"))
            continue
        body = render(spu, skus.get(sid, []), DATA[sid])
        docs.append((sid, spu["name"], DATA[sid]["tags"], body, len(skus.get(sid, []))))

    print(f"[计划] 待入库 {len(docs)} 篇，跳过 {len(skipped)} 个")
    for sid, reason in skipped:
        print(f"  - SPU {sid} 跳过：{reason}")
    for sid, name, tags, body, nsku in docs:
        print(f"  + SPU {sid} {name}｜tags={tags}｜SKU {nsku}｜{len(body)} 字符")

    if args.out_dir:
        out = Path(args.out_dir)
        out.mkdir(parents=True, exist_ok=True)
        for sid, name, _t, body, _n in docs:
            (out / f"{name} 产品规格.md").write_text(body, encoding="utf-8")
        print(f"[输出] 已写入 {out}")

    if args.dry_run:
        if docs:
            print("\n----- 样例（第一篇） -----\n")
            print(docs[0][3])
        return 0

    from app.core.security import create_access_token

    headers = {"Authorization": f"Bearer {create_access_token(1, extra={'role': 'ADMIN'})}"}
    ok_cnt, fail = 0, []
    for idx, (sid, name, tags, body, _n) in enumerate(docs, 1):
        # 文件名不能含路径分隔符：知识库服务直接把它拼到 uploads 目录下，
        # 出现 "/" 会当作子目录导致 FileNotFoundError（如「冰吧/红酒柜」）
        safe_name = name.replace("/", " ").replace("\\", " ")
        filename = f"{safe_name} 产品规格.md"
        try:
            r = requests.post(
                f"{BASE}/kb/documents", headers=headers,
                files={"file": (filename, body.encode("utf-8"), "text/markdown")},
                data={"tags": tags}, timeout=180)
            data = (r.json() or {}).get("data") or {}
            if r.status_code == 200 and data.get("status") == "ready":
                ok_cnt += 1
                print(f"[{idx}/{len(docs)}] OK  {name}  chunks={data.get('chunk_count')}")
            else:
                fail.append((name, r.status_code, str(r.json())[:200]))
                print(f"[{idx}/{len(docs)}] FAIL {name}  {r.status_code} {str(r.json())[:200]}")
        except Exception as e:  # noqa
            fail.append((name, "exc", str(e)[:200]))
            print(f"[{idx}/{len(docs)}] ERR  {name}  {e}")

    print(f"\n[完成] 成功 {ok_cnt} / {len(docs)}，失败 {len(fail)}")
    for f in fail:
        print("  !", f)
    return 0 if not fail else 1


if __name__ == "__main__":
    raise SystemExit(main())
